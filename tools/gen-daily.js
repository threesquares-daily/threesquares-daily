// Pre-generates the daily puzzles. Day 1 = 2026-11-02 (Monday).
const fs = require('fs');
const TS = require('../engine.js');
const DAYS = +process.argv[2] || 365;
const STAR = [6, 7, 7, 8, 8, 8, 9];
const DUO = [
  { givens: 9, edges: 5, maxLook: 1 },
  { givens: 8, edges: 5, maxLook: 1 },
  { givens: 6, edges: 6, minLook: 1, maxLook: 4 },
  { givens: 6, edges: 6, minLook: 1, maxLook: 4 },
  { givens: 5, edges: 6, minLook: 2 },
  { givens: 3, edges: 7, minLook: 3 },
  { givens: 3, edges: 7, minLook: 4 },
];
const THREAD = [[6, 10], [6, 8], [6, 0], [7, 13], [7, 11], [7, 0], [7, 0]];
const out = [];
const t0 = Date.now();
for (let d = 0; d < DAYS; d++) {
  const wd = d % 7;
  let s = null, k = 0;
  while (!s) s = TS.genStars(STAR[wd], TS.rng(TS.hashSeed('stars-' + d + '-' + k++)));
  let du = null; k = 0;
  while (!du) du = TS.genDuo(TS.rng(TS.hashSeed('duo-' + d + '-' + k++)), DUO[wd]);
  let th = null; k = 0;
  const [tn, target] = THREAD[wd];
  while (!th) th = TS.genThread(tn, TS.rng(TS.hashSeed('thread-' + d + '-' + k++)), { nums: 6, target });
  out.push({
    s: { n: s.n, r: s.r },
    d: { g: du.g, e: du.e.map(([a, b, t]) => a + t + b).join(',') },
    t: { n: th.n, k: th.k.map(([c]) => c).join(',') },
  });
  if (d % 20 === 0) console.log('day', d + 1, 'elapsed', ((Date.now() - t0) / 1000).toFixed(0) + 's');
}
fs.writeFileSync(__dirname + '/../daily.js',
  '/* Three Squares daily puzzles. Day 1 = 2026-11-02. Generated by tools/gen-daily.js */\n' +
  'window.TS_DAILY={start:"2026-11-02",days:' + JSON.stringify(out) + '};\n');
console.log('done', DAYS, 'days in', ((Date.now() - t0) / 1000).toFixed(0) + 's');
